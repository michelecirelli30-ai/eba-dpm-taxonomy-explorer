'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const T=require('../docs/data/eba_rule_translator.js');
const db=JSON.parse(fs.readFileSync(path.join(__dirname,'../docs/data/corep_c0100_official.json'),'utf8'));
const rules=db.validation_rules.filter(r=>r.type==='validation');
assert.equal(rules.length,52,'expected exactly 52 EBA source validation rules');
const find=id=>rules.find(r=>r.code===id);
const a=T.interpret(find('v0175_m').expression,db.cells);
assert.equal(a.status,'supported',JSON.stringify(a.reason));
assert.match(a.plainEnglish,/Retained earnings must equal previous years retained earnings plus eligible profit or loss/i);
assert.ok(a.references.some(r=>r.row==='0130'&&r.column==='0010'&&r.cellId===18));
assert.equal(a.references.length,3);
assert.ok(a.technical.some(x=>x.includes('default: 0')));
assert.ok(a.technical.some(x=>x.includes('interval: true')));
const compact=T.readableStructure(a);
assert.equal(compact.termCount,2);
assert.equal(compact.long,false);
const b=T.interpret(find('v0172_m').expression,db.cells);
assert.equal(b.status,'supported',JSON.stringify(b.reason));
assert.ok(b.references.length>=10);
const expanded=T.readableStructure(b);
assert.equal(expanded.long,true);
assert.equal(expanded.termCount,31);
assert.equal(expanded.lhs.row,'0020');
assert.equal(expanded.terms[0].row,'0030');
assert.ok(expanded.signedMarkedCount>0);
assert.match(expanded.caution,/reported value with its algebraic sign/i);

// EBA DPM 2.0 explicit row-set selectors: comparisons are cell-wise, not sums.
const nonNegative=T.interpret(find('v3684_s').expression,db.cells);
assert.equal(nonNegative.status,'supported',JSON.stringify(nonNegative.reason));
const nonNegativeSet=T.rowSetStructure(nonNegative);
assert.equal(nonNegativeSet.count,29);
assert.equal(nonNegativeSet.operator,'>=');
assert.equal(nonNegativeSet.defaultValue,'null');
assert.equal(nonNegativeSet.interval,'false');
assert.equal(nonNegativeSet.members[0].row,'0040');
assert.equal(nonNegativeSet.members[0].cellId,9);
assert.equal(nonNegativeSet.members.at(-1).row,'0970');
assert.ok(nonNegativeSet.members.every(x=>x.label&&x.cellId!=null&&x.variableVid!=null));
assert.match(nonNegative.plainEnglish,/each of the 29 selected reporting cells/i);
assert.match(nonNegative.businessFormula,/evaluated per selected cell, not as a sum/i);
const nonPositive=T.interpret(find('v3685_s').expression,db.cells);
assert.equal(nonPositive.status,'supported',JSON.stringify(nonPositive.reason));
const nonPositiveSet=T.rowSetStructure(nonPositive);
assert.equal(nonPositiveSet.count,55);
assert.equal(nonPositiveSet.operator,'<=');
assert.equal(nonPositiveSet.members[0].row,'0070');
assert.equal(nonPositiveSet.members.at(-1).row,'0974');
assert.equal(nonPositive.references.length,55);
assert.ok(nonPositiveSet.members.every(x=>x.label&&x.cellId!=null));
assert.match(nonPositive.plainEnglish,/less than or equal to zero/i);
// Fail closed on unsupported groups or unverifiable source cells.
const groupPrelude="with {tC_01.00, c0010, default: null, interval: false}: ";
assert.equal(T.interpret(groupPrelude+'{(r0040, r0040)} >= 0',db.cells).status,'requires_review');
assert.equal(T.interpret(groupPrelude+'{(r0040, r9999)} >= 0',db.cells).status,'requires_review');
assert.equal(T.interpret(groupPrelude+'{(r0040, r0045)} > 0',db.cells).status,'requires_review');
assert.equal(T.interpret(groupPrelude+'{(r0040, r0045)} + {r0060} >= 0',db.cells).status,'requires_review');
assert.equal(T.interpret('with {tC_01.00, c0010, default: 0, interval: true}: {(r0040, r0045)} >= 0',db.cells).status,'requires_review');
assert.equal(T.interpret(groupPrelude+'{(r0040-r0045)} >= 0',db.cells).status,'requires_review');
assert.equal(T.interpret('{(r0040, r0045)} >= 0',db.cells).status,'requires_review');
assert.equal(T.rowSetStructure(a),null);
assert.equal(T.readableStructure(nonPositive),null);
const bad=T.interpret('with {tC_01.00, c0010}: {r0130} ??? {r0140}',db.cells);
assert.equal(bad.status,'requires_review');
const incomplete=T.interpret('with {tC_01.00, c0010}: {r9999} = {r0130}',db.cells);
assert.equal(incomplete.status,'requires_review');
const cross=T.interpret('with {c0010}: {tC_04.00, r0030} = {tC_01.00, r0130}',db.cells);
assert.equal(cross.status,'requires_review');
const coverage=T.summary(db.validation_rules,db.cells);
assert.equal(coverage.total,52);
assert.equal(coverage.total,coverage.supported+coverage.requires_review);
assert.equal(coverage.supported,28);
assert.equal(coverage.requires_review,24);
console.log('Rule translator: corpus coverage',JSON.stringify(coverage,null,2));
console.log('PASS: v0175_m, v0172_m, unsupported syntax, row sets v3684_s / v3685_s, strict review fallback, corpus coverage');
